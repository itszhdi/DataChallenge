def _norm(text: str) -> str:
    return re.sub(r"\s+", " ", (text or "").strip().lower())


def playbook_for(c: dict[str, Any]) -> dict[str, str] | None:
    entry = PLAYBOOK.get(c.get("id", ""))
    if entry and _norm(entry["rule"]) == _norm(c.get("rule", "")):
        return entry
    return None


def _answer_hint(c: dict[str, Any]) -> str:
    if c["type"] == "binary":
        return "value: 1 = Да, 0 = Нет."
    if c["type"] == "flag":
        types = ", ".join(c.get("flag_types") or [])
        return f"value: 1 = нарушение выявлено, 0 = не выявлено. flags: типы нарушений ({types}); пустой список, если value = 0."
    steps = ", ".join(str(s["value"]) for s in sorted(c.get("scale", []), key=lambda s: -s["value"]))
    return f"value: строго одна из ступеней ({steps}), промежуточные значения запрещены."


def render_criterion(c: dict[str, Any]) -> str:
    scale_txt = "ДА/НЕТ" if c["type"] == "binary" else ("ФЛАГ" if c["type"] == "flag" else "ШКАЛА")
    na_txt = f"N/A разрешён: {c['na_condition']}" if c.get("na_allowed") else "N/A ЗАПРЕЩЁН"
    lines = [
        f"### {c['id']} — {c.get('title', '')} ({scale_txt}, вес {c.get('weight', 0)}, {na_txt})",
        f"Правило: {c.get('rule', '')}",
    ]
    if c["type"] == "scale":
        lines.append("Ступени:")
        lines += [f"  {s['value']} — {s.get('description', '')}" for s in sorted(c["scale"], key=lambda s: -s["value"])]
    pb = playbook_for(c)
    if pb:
        lines.append(f"Алгоритм проверки: {pb['algorithm']}")
        lines.append(f"Ловушки: {pb['traps']}")
    if c.get("guidance"):
        lines.append(f"Пояснение: {c['guidance']}")
    for ex in c.get("examples_pass") or []:
        lines.append(f"Пример «Да»: {ex}")
    for ex in c.get("examples_fail") or []:
        lines.append(f"Пример «Нет»: {ex}")
    lines.append(f"Как отвечать: {_answer_hint(c)}")
    return "\n".join(lines)


def generate_rubric_text(criteria: list[dict[str, Any]]) -> str:
    return "\n\n".join(render_criterion(c) for c in criteria)


