def render_timing(facts: dict[str, Any]) -> str:
    thr = facts["threshold_sec"]
    lines = [f"Порог первой реакции: {thr} с ({thr // 60} мин)."]
    if facts["first_response_sec"] is None:
        lines.append("Первая реакция оператора на клиента: не определена (нет ответа оператора после реплики клиента или нет времени).")
    else:
        verdict = "ПРЕВЫШЕН" if facts["first_response_exceeded"] else "не превышен"
        lines.append(
            f"Первая реакция оператора: #{facts['first_operator_reply_index']} через {facts['first_response_sec']:.0f} с "
            f"после первой реплики клиента #{facts['first_client_index']} — порог {verdict}."
        )
    if facts["long_pauses"]:
        pauses = "; ".join(f"#{p['client_index']}→#{p['operator_index']}: {p['seconds']:.0f} с" for p in facts["long_pauses"])
        lines.append(f"Паузы клиент→оператор дольше порога: {pauses}. Проверь, предупреждал ли оператор об ожидании.")
    else:
        lines.append("Пауз клиент→оператор дольше порога нет.")
    return "\n".join(lines)


def render_transcript(transcript: list[dict[str, Any]]) -> str:
    # * Формат строки: [#3] 01:10 оператор: текст — время как смещение от начала, номер реплики = ссылка для UI
    return "\n".join(
        f"[#{m['index']}] {format_offset(m['offset_sec'])} {SPEAKER_RU.get(m['speaker'], m['speaker'])}: {m.get('text', '')}"
        for m in with_offsets(transcript)
    )


def select_criteria(checklist: dict[str, Any], criteria_ids: list[str] | None = None) -> list[dict[str, Any]]:
    if criteria_ids is None:
        return list(checklist["criteria"])
    wanted = set(criteria_ids)
    return [c for c in checklist["criteria"] if c["id"] in wanted]


def build_messages(
    checklist: dict[str, Any], conversation: dict[str, Any], criteria: list[dict[str, Any]]
) -> list[dict[str, str]]:
    # * Слои user-промпта: метаданные → рубрика → время → транскрипт → финальная инструкция (recency)
    settings = checklist.get("settings", {})
    threshold = int(settings.get("first_response_threshold_sec", 180))
    lang = conversation.get("language") or "?"
    channel = conversation.get("channel") or "?"
    n = len(conversation["transcript"])
    ids = ", ".join(c["id"] for c in criteria)
    user = "\n\n".join([
        f"## Метаданные\nДиалог: {conversation.get('id') or conversation.get('conversation_id') or '?'}. Канал: {channel}. "
        f"Язык клиента (метка): {LANG_RU.get(lang, lang)} ({lang}). Реплик: {n} (#1–#{n}).",
        "## Чек-лист (оцени каждый критерий)\n" + generate_rubric_text(criteria),
        LANGUAGE_CHEATSHEET,
        "## Факты о времени (вычислены кодом, им можно доверять)\n" + render_timing(timing_facts(conversation["transcript"], threshold)),
        "## Транскрипт\n" + render_transcript(conversation["transcript"]),
        f"## Задание\nВерни JSON с ключами: {ids}. Для каждого: explanation (рус.) → evidence_ids → quote (дословно, язык оригинала) → "
        f"quote_ref → checked_range → needs_review → unverified_claims → na (если есть) → value (+ flags для флага). "
        f"unverified_claims — конкретные неподтверждённые утверждения оператора, иначе []; needs_review согласуй с этим списком. "
        f"value должен совпадать с выводом в explanation.",
    ])
    return [{"role": "system", "content": SYSTEM_PROMPT}, {"role": "user", "content": user}]


def criterion_schema(c: dict[str, Any]) -> dict[str, Any]:
    # ** Порядок полей = порядок генерации: рассуждение → доказательства → применимость → оценка
    props: dict[str, Any] = {
        "explanation": {"type": "string", "description": "На русском: что требовалось → что сделал оператор (#N) → «Вывод: …»"},
        "evidence_ids": {"type": "array", "items": {"type": "integer"}},
        "quote": {"type": "string", "description": "Дословная подстрока одной реплики, без перевода"},
        "quote_ref": {"type": "integer", "description": "Номер реплики с цитатой, 0 если цитаты нет"},
        "checked_range": {"type": "string", "description": "Проверенный участок, например #2–#6"},
        "needs_review": {"type": "boolean", "description": "Требуется ручная проверка утверждения или доказательств"},
        "unverified_claims": {"type": "array", "items": {"type": "string"}, "description": "Конкретные неподтверждённые утверждения оператора; [] если нет"},
    }
    if c.get("na_allowed"):
        props["na"] = {"type": "boolean"}
    if c["type"] == "scale":
        props["value"] = {"type": "integer", "enum": [int(s["value"]) for s in c["scale"]]}
    else:
        props["value"] = {"type": "integer", "enum": [0, 1]}
    if c["type"] == "flag" and c.get("flag_types"):
        props["flags"] = {"type": "array", "items": {"type": "string", "enum": list(c["flag_types"])}}
    return {"type": "object", "properties": props, "required": list(props), "additionalProperties": False}


def build_schema(criteria: list[dict[str, Any]]) -> dict[str, Any]:
    return {
        "type": "object",
        "properties": {c["id"]: criterion_schema(c) for c in criteria},
        "required": [c["id"] for c in criteria],
        "additionalProperties": False,
    }


def ground_answers(raw: dict[str, Any], transcript: list[dict[str, Any]]) -> dict[str, Any]:
    # * Проверка цитат: дословная подстрока → номер реплики добавляется в evidence_ids; иначе цитата помечается
    texts = [_norm(m.get("text", "")) for m in transcript]
    for cid, a in raw.items():
        if not isinstance(a, dict):
            continue
        quote = _norm(a.get("quote", ""))
        if not quote:
            continue
        ref = a.get("quote_ref") if isinstance(a.get("quote_ref"), int) else 0
        hit = ref if 1 <= ref <= len(texts) and quote in texts[ref - 1] else next(
            (i for i, t in enumerate(texts, start=1) if quote in t), 0
        )
        if hit:
            a["quote_ref"] = hit
            ids = a.setdefault("evidence_ids", [])
            if hit not in ids:
                ids.append(hit)
            a["quote_verified"] = True
        else:
            a["quote_verified"] = False
            logger.warning("Quote for %s not found verbatim in transcript: %r", cid, a.get("quote", "")[:80])
    return raw


def preview(checklist: dict[str, Any], conversation: dict[str, Any], criteria_ids: list[str] | None = None) -> dict[str, Any]:
    criteria = select_criteria(checklist, criteria_ids)
    messages = build_messages(checklist, conversation, criteria)
    return {
        "version": PROMPT_VERSION,
        "messages": messages,
        "schema": build_schema(criteria),
        "chars": len(json.dumps(messages, ensure_ascii=False)),
    }
